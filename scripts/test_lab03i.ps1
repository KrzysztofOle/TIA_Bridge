# Requires Windows PowerShell 5.1 x64, PowerShell 7, the built lab exporter and Esprima.dll.
# Offline only: invokes the existing splitter/validator/publisher; never calls Siemens.
param([string]$LabRoot = 'X:\TESTY_TIA_Bridge')
$ErrorActionPreference = 'Stop'
$token = [guid]::NewGuid().ToString('N')
$run = Join-Path $LabRoot "evidence\LAB-03I-offline-$token"
$exports = Join-Path $LabRoot "exports\LAB-03I-offline-$token"
New-Item -ItemType Directory -Path $run,$exports | Out-Null
$type = [Reflection.Assembly]::LoadFrom((Join-Path $LabRoot 'bin\LabExporter.exe')).GetType('LabExporter', $true)
$utf8 = New-Object Text.UTF8Encoding($false, $true)
$results = New-Object 'Collections.Generic.List[object]'
function Call([string]$Name, [object[]]$Arguments) {
    $method = $type.GetMethod($Name, [Reflection.BindingFlags]'NonPublic,Static')
    $parameters = $method.GetParameters()
    for ($i=0; $i -lt $Arguments.Length; $i++) {
        if ($parameters[$i].ParameterType -eq [string]) { $Arguments[$i] = [string]$Arguments[$i] }
    }
    try { $null = $method.Invoke($null, $Arguments) }
    catch { if ($_.Exception.InnerException) { throw $_.Exception.InnerException }; throw }
}
function Assert([bool]$Ok, [string]$Message) { if (-not $Ok) { throw $Message } }
function Test([string]$Name, [scriptblock]$Body) {
    try { & $Body; $results.Add([ordered]@{name=$Name; status='PASS'}) }
    catch { $results.Add([ordered]@{name=$Name; status='FAIL'; error=($_.Exception.ToString() + "`n" + $_.ScriptStackTrace)}) }
}
function Hash([string]$Path) { (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash }
function Json-Write($Value, [string]$Path) { [IO.File]::WriteAllText($Path, ($Value | ConvertTo-Json -Depth 30), $utf8) }
function Split([string]$Native, [string]$Package) {
    $ErrorActionPreference = 'Continue' # Capture native stderr and exit code as evidence.
    $log = & pwsh.exe -NoProfile -File (Join-Path $LabRoot 'src\SplitModules.ps1') -NativeExportRoot $Native -PackageRoot $Package -ScopeBinding 'synthetic-lab03i' -EsprimaAssembly (Join-Path $LabRoot 'bin\Esprima.dll') 2>&1
    $code = $LASTEXITCODE
    $log | Out-File -LiteralPath ($Package + '.log') -Encoding utf8
    if ($code -ne 0) { throw "SPLIT_FAILED: $log" }
}
function Prepare([string]$Package) {
    $dest = Join-Path $run ([guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Path $dest | Out-Null
    Call 'PrepareForceImportInput' @($Package,$dest)
    return $dest
}
function Clone-Package {
    $dest = Join-Path $exports ([guid]::NewGuid().ToString('N'))
    Call 'CopyDirectory' @($script:package,$dest)
    return $dest
}
function Reject([string]$Package, [string]$Pattern) {
    $caught = $null
    try { $null = Prepare $Package } catch { $caught = $_.Exception.ToString() }
    Assert ($null -ne $caught -and $caught -match $Pattern) "Expected rejection $Pattern; actual: $caught"
}
$native = Join-Path $exports 'native'
$package = Join-Path $exports 'package'
$variants = @(
    @{name='UnicodeCrLf'; eol="`r`n"; global='const label = "za' + [char]0x17c + [char]0xf3 + [char]0x142 + [char]0x107 + ' ' + [char]::ConvertFromUtf32(0x1f600) + '";'; bom=$false},
    @{name='EmptyLf'; eol="`n"; global=''; bom=$false},
    @{name='BomLf'; eol="`n"; global='const label = "' + [char]0x65e5 + [char]0x672c + [char]0x8a9e + '";'; bom=$true}
)
foreach ($v in $variants) {
    $dir = Join-Path $native ($v.name + '\native')
    New-Item -ItemType Directory -Path $dir -Force | Out-Null
    $source = (@($v.global,'/*<auto-generated>','***End of Global definition area***','Changes to this comment may cause incorrect behavior during document based import.','</auto-generated>*/',('export function alpha() { return "' + [char]0x105 + '"; }'),'','export function beta() { return 2; }','') -join $v.eol)
    if ($v.bom) { $source = [char]0xFEFF + $source }
    [IO.File]::WriteAllBytes((Join-Path $dir ($v.name+'.hmi.js')), $utf8.GetBytes($source))
    [IO.File]::WriteAllText((Join-Path $dir ($v.name+'.hmi.yml')), ("#Version: 2.0`r`nModules:`r`n  " + $v.name + ":`r`n    ScriptFile: " + $v.name + ".hmi.js`r`n"), $utf8)
}
Test 'export_new_filename_utf8_bom_crlf_lf_empty_global' { Split $native $package; Call 'ValidatePackage' @($package) }
if (Test-Path -LiteralPath (Join-Path $package 'manifest.json')) {
    Test 'no_legacy_files_and_both_manifest_levels' {
        Assert (@(Get-ChildItem -LiteralPath $package -Recurse -Filter 'Global definition area.js').Count -eq 0) 'legacy file exported'
        $root = Get-Content (Join-Path $package 'manifest.json') -Raw | ConvertFrom-Json
        Assert ($root.schema_version -ceq 'lab-03i-scripts-manifest/1.0') 'root schema'
        foreach ($row in $root.modules) {
            $m = Get-Content (Join-Path $package ($row.module_name+'\.native\manifest.json')) -Raw | ConvertFrom-Json
            Assert ($m.schema_version -ceq 'lab-03i-module-manifest/1.0' -and $m.parts[0].path -ceq '_Global_definition_area.js' -and $row.parts[0].path -ceq '_Global_definition_area.js' -and $m.parts[0].kind -ceq 'GLOBAL_PREFIX' -and $m.parts[1].name -ceq 'alpha' -and $m.parts[2].name -ceq 'beta') 'manifest global/order'
        }
    }
    Test 'sha256_byte_identity_and_siemens_metadata' {
        $built = Prepare $package
        foreach ($v in $variants) {
            foreach ($ext in 'hmi.js','hmi.yml') {
                Assert ((Hash (Join-Path $native ($v.name+'\native\'+$v.name+'.'+$ext))) -ceq (Hash (Join-Path $built ($v.name+'.'+$ext)))) ('byte mismatch '+$v.name+'.'+$ext)
                Assert ([Collections.StructuralComparisons]::StructuralEqualityComparer.Equals([IO.File]::ReadAllBytes((Join-Path $native ($v.name+'\native\'+$v.name+'.'+$ext))),[IO.File]::ReadAllBytes((Join-Path $built ($v.name+'.'+$ext))))) 'direct byte comparison failed'
            }
        }
    }
    Test 'offline_rebuild_helper_uses_current_force_import' {
        $dest = Join-Path $run 'helper-built'
        $log = & powershell.exe -NoProfile -File (Join-Path $LabRoot 'src\RebuildImportPackages.ps1') -ScriptsRoot $package -Destination $dest 2>&1
        Assert ($LASTEXITCODE -eq 0) "Helper failed: $log"
        Assert ((Hash (Join-Path $dest 'BomLf.hmi.js')) -ceq (Hash (Join-Path $native 'BomLf\native\BomLf.hmi.js'))) 'helper changed BOM source'
    }
    Test 'edited_function_only_other_slices_and_metadata_unchanged' {
        $copy = Clone-Package
        $file = Join-Path $copy 'UnicodeCrLf\alpha.js'
        [IO.File]::WriteAllBytes($file, $utf8.GetBytes(([IO.File]::ReadAllText($file,$utf8)).Replace(('return "' + [char]0x105 + '"'),'return "zmiana"')))
        $built = Prepare $copy
        $before = [IO.File]::ReadAllText((Join-Path $native 'UnicodeCrLf\native\UnicodeCrLf.hmi.js'),$utf8)
        $expected = $utf8.GetBytes($before.Replace(('return "' + [char]0x105 + '"'),'return "zmiana"'))
        $actual = [IO.File]::ReadAllBytes((Join-Path $built 'UnicodeCrLf.hmi.js'))
        Assert ([Collections.StructuralComparisons]::StructuralEqualityComparer.Equals($expected,$actual)) 'edited bundle differs beyond selected function'
        foreach ($v in $variants) {
            Assert ((Hash (Join-Path $built ($v.name+'.hmi.yml'))) -ceq (Hash (Join-Path $native ($v.name+'\native\'+$v.name+'.hmi.yml')))) 'metadata changed'
            Assert ((Hash (Join-Path $copy ($v.name+'\beta.js'))) -ceq (Hash (Join-Path $package ($v.name+'\beta.js')))) 'beta changed'
            if ($v.name -ne 'UnicodeCrLf') { Assert ((Hash (Join-Path $built ($v.name+'.hmi.js'))) -ceq (Hash (Join-Path $native ($v.name+'\native\'+$v.name+'.hmi.js')))) 'other module changed' }
        }
    }
    Test 'missing_function_rejected' { $c=Clone-Package; [IO.File]::Delete((Join-Path $c 'UnicodeCrLf\beta.js')); Reject $c 'MODULE_PART_MISSING' }
    Test 'missing_global_rejected' { $c=Clone-Package; [IO.File]::Delete((Join-Path $c 'UnicodeCrLf\_Global_definition_area.js')); Reject $c 'MODULE_PART_MISSING' }
    Test 'both_global_names_rejected_without_source_mutation' {
        $c=Clone-Package; $f=Join-Path $c 'UnicodeCrLf\Global definition area.js'; [IO.File]::WriteAllText($f,'legacy',$utf8)
        $hash=Hash $f; Reject $c 'GLOBAL_DEFINITION_NAMES_CONFLICT'; Assert ((Hash $f) -ceq $hash) 'input migrated'
    }
    Test 'legacy_filename_rejected_with_force_export_message' {
        $c=Clone-Package; [IO.File]::Move((Join-Path $c 'UnicodeCrLf\_Global_definition_area.js'),(Join-Path $c 'UnicodeCrLf\Global definition area.js')); Reject $c 'LEGACY_GLOBAL_DEFINITION_FORMAT[\s\S]*FORCE EXPORT'
    }
    Test 'legacy_schema_rejected_with_force_export_message' {
        $c=Clone-Package; $f=Join-Path $c 'manifest.json'; $m=Get-Content $f -Raw|ConvertFrom-Json; $m.schema_version='lab-03g-scripts-manifest/1.0'; Json-Write $m $f; Reject $c 'LEGACY_GLOBAL_DEFINITION_FORMAT[\s\S]*FORCE EXPORT'
    }
    Test 'stale_root_manifest_rejected' {
        $c=Clone-Package; $f=Join-Path $c 'manifest.json'; $m=Get-Content $f -Raw|ConvertFrom-Json; $m.modules[0].parts[0].path='Global definition area.js'; Json-Write $m $f; Reject $c 'ROOT_MODULE_PART_MISMATCH'
    }
    Test 'stale_module_schema_rejected' {
        $c=Clone-Package; $f=Join-Path $c 'UnicodeCrLf\.native\manifest.json'; $m=Get-Content $f -Raw|ConvertFrom-Json; $m.schema_version='lab-03g-module-manifest/1.0'; Json-Write $m $f; Reject $c 'MODULE_MANIFEST_INVALID'
    }
    Test 'metadata_tamper_rejected' { $c=Clone-Package; [IO.File]::AppendAllText((Join-Path $c 'UnicodeCrLf\.native\UnicodeCrLf.hmi.yml'),'tamper',$utf8); Reject $c 'MODULE_NATIVE_METADATA_INVALID' }
    Test 'native_js_tamper_rejected' { $c=Clone-Package; [IO.File]::AppendAllText((Join-Path $c 'UnicodeCrLf\.native\UnicodeCrLf.hmi.js'),'tamper',$utf8); Reject $c 'MODULE_NATIVE_ARTIFACT_INVALID' }
    Test 'export_part_sha256_tamper_rejected' {
        $c=Clone-Package; [IO.File]::AppendAllText((Join-Path $c 'UnicodeCrLf\alpha.js'),'tamper',$utf8)
        $caught=$false; try { Call 'ValidatePackage' @($c) } catch { $caught=$_.Exception.ToString() -match 'MANIFEST_HASH_MISMATCH' }; Assert $caught 'export hash tamper accepted'
    }
    Test 'global_cannot_be_function_or_move_after_functions' {
        $c=Clone-Package
        foreach ($f in @((Join-Path $c 'manifest.json'),(Join-Path $c 'UnicodeCrLf\.native\manifest.json'))) {
            $m=Get-Content $f -Raw|ConvertFrom-Json
            $row=if ($m.modules) { $m.modules|Where-Object module_name -eq UnicodeCrLf } else { $m }
            $row.parts[0].kind='EXPORTED_FUNCTION'; Json-Write $m $f
        }
        Reject $c 'MODULE_GLOBAL_PREFIX_MISSING'
    }
    Test 'reserved_function_name_collision_rejected' {
        $n=Join-Path $exports 'collision-native'; $d=Join-Path $n 'Collision\native'; New-Item -ItemType Directory -Path $d -Force|Out-Null
        [IO.File]::WriteAllText((Join-Path $d 'Collision.hmi.js'), "/*<auto-generated>`n***End of Global definition area***`n</auto-generated>*/`nexport function _Global_definition_area() {}`n",$utf8)
        [IO.File]::WriteAllText((Join-Path $d 'Collision.hmi.yml'),'opaque',$utf8)
        $caught=$false; try { Split $n (Join-Path $exports 'collision-package') } catch { $caught=$_.Exception.ToString() -match 'FUNCTION_NAME_COLLISION' }; Assert $caught 'reserved name exported as function'
    }
    Test 'publish_new_package_removes_legacy_and_cross_volume_sha256' {
        $out=Join-Path $run 'published'; New-Item -ItemType Directory -Path $out|Out-Null
        [IO.File]::WriteAllText((Join-Path $out 'Global definition area.js'),'old',$utf8)
        $stage=Join-Path $run 'stage'; $backup=Join-Path $run 'backup'
        Call 'CopyDirectory' @($package,$stage); Call 'VerifyDirectoryCopy' @($package,$stage); Call 'ValidatePackage' @($stage)
        Call 'ReplaceOutputWithRollback' @($stage,$out,$backup,$null); Call 'ValidatePackage' @($out)
        Assert (-not (Test-Path (Join-Path $out 'Global definition area.js'))) 'legacy survived publish'
        Assert (Test-Path (Join-Path $backup 'Global definition area.js')) 'backup missing'
        $cross=Join-Path $env:TEMP ('LAB-03I-stage-'+$token)
        Call 'CopyDirectory' @($package,$cross); Call 'VerifyDirectoryCopy' @($package,$cross); Call 'ValidatePackage' @($cross)
    }
