$report=[ordered]@{ task='LAB-03I'; status=$(if ($failed -eq 0) {'PASS'} else {'FAIL'}); passed=$results.Count-$failed; failed=$failed; evidence=$run; fixtures=$exports; results=$results.ToArray(); binary_sha256=(Hash (Join-Path $LabRoot 'bin\LabExporter.exe')) }
Json-Write $report (Join-Path $run 'results.json')
